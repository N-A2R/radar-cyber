/**
 * TheHive case connector.
 *
 * Only Nouvelle-Aquitaine alerts can become cases. Alert scopes reserved for
 * human review never leave the platform. Case content is built exclusively
 * from structured, public fields: no event title, summary, evidence or other
 * free text can leak a victim's personal data into TheHive. Source trust is
 * intentionally not checked — gray sources stay eligible.
 */
import { ALERT_SCOPES_REVUE } from "../alert-scope.js";
import { NA_DEPARTMENTS } from "../filiation/siret.js";

export interface TheHiveAlert {
	id: number;
	ruleId: string;
	severity: number;
	scope: string;
	regional: boolean;
	organizationName: string | null;
	organizationDept: string | null;
	eventFamily: string | null;
	sourceName: string | null;
	sourceUrl: string | null;
	observedAt: string | null;
}

/** Fields accepted by the TheHive `POST /api/case` endpoint. */
export interface TheHiveCasePayload {
	title: string;
	description: string;
	severity: number;
	tags: string[];
	externalRef: string;
}

export interface TheHiveClient {
	createCase(payload: TheHiveCasePayload): Promise<string>;
}

export interface TheHiveConfig {
	url: string;
	apiKey: string;
	fetch?: typeof fetch;
}

export type Eligibility = "eligible" | "outside-region" | "review-only";

const REVIEW_ONLY_SCOPES: ReadonlySet<string> = new Set([
	...ALERT_SCOPES_REVUE,
	"rupture",
	"supervision-silent-source",
]);

const EMAIL = /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/gi;
const PHONE = /(?:\+33[\s.-]?|0)[1-9](?:[\s.-]?\d){8}/g;
const URL_CREDENTIALS = /(https?:\/\/)[^/@\s]+@/gi;

/** Last line of defence: structured fields are never victim free text. */
export function redactPersonalData(value: string | null | undefined, max = 300): string {
	return String(value ?? "")
		.normalize("NFKC")
		.replace(/[\u0000-\u001f\u007f]/g, " ")
		.replace(URL_CREDENTIALS, "$1[redacted]@")
		.replace(EMAIL, "[redacted]")
		.replace(PHONE, "[redacted]")
		.replace(/\s+/g, " ")
		.trim()
		.slice(0, max);
}

function slug(value: string | null | undefined): string {
	return redactPersonalData(value, 80)
		.normalize("NFKD")
		.toLowerCase()
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-+|-+$/g, "")
		.slice(0, 60) || "unknown";
}

const SEVERITY_LABELS: Record<number, string> = {
	1: "info", 2: "low", 3: "medium", 4: "high", 5: "critical",
};

/** Radar uses 1–5, TheHive 1–4. */
export function toTheHiveSeverity(radarSeverity: number): number {
	if (!Number.isInteger(radarSeverity)) return 2;
	const map: Record<number, number> = { 1: 1, 2: 1, 3: 2, 4: 3, 5: 4 };
	return map[radarSeverity] ?? 2;
}

export function eligibility(alert: TheHiveAlert): Eligibility {
	if (REVIEW_ONLY_SCOPES.has(alert.scope)) return "review-only";
	const dept = alert.organizationDept?.trim() ?? "";
	if (!alert.regional && !(dept && NA_DEPARTMENTS[dept] === true)) return "outside-region";
	return "eligible";
}

/** Build one case from an alert. No free text from events or evidence. */
export function buildCase(alert: TheHiveAlert): TheHiveCasePayload {
	const dept = alert.organizationDept?.trim() ?? "";
	const region = NA_DEPARTMENTS[dept] === true ? `Nouvelle-Aquitaine (${dept})` : "Nouvelle-Aquitaine";
	const org = redactPersonalData(alert.organizationName, 120) || "unspecified organization";
	const rule = redactPersonalData(alert.ruleId, 80) || "unspecified-rule";
	const observed = alert.observedAt && !Number.isNaN(Date.parse(alert.observedAt))
		? new Date(alert.observedAt).toISOString()
		: "unknown";
	const description = [
		"Generated by radar-cyber from a Nouvelle-Aquitaine alert.",
		`Alert ID: ${alert.id}`,
		`Rule: ${rule}`,
		`Radar severity: ${alert.severity} (${SEVERITY_LABELS[alert.severity] ?? "unknown"})`,
		`Region: ${region}`,
		`Organization: ${org}`,
		`Event family: ${redactPersonalData(alert.eventFamily, 80) || "unknown"}`,
		`Source: ${redactPersonalData(alert.sourceName, 120) || "unknown"}`,
		`Source URL: ${redactPersonalData(alert.sourceUrl, 300) || "none"}`,
		`Observed at: ${observed}`,
	].join("\n");

	return {
		title: `[Radar Cyber] Alert ${alert.id} - ${rule} - ${org}`,
		description,
		severity: toTheHiveSeverity(alert.severity),
		tags: ["radar-cyber", "nouvelle-aquitaine", `dept:${dept || "na"}`, `rule:${slug(alert.ruleId)}`],
		externalRef: `radar-cyber:alert:${alert.id}`,
	};
}

export interface CasePlan {
	cases: Array<{ alertId: number; payload: TheHiveCasePayload }>;
	skipped: { outsideRegion: number; reviewOnly: number; duplicate: number };
}

/** Pure planning step, shared by the API preview and the creation pipeline. */
export function planCases(alerts: readonly TheHiveAlert[]): CasePlan {
	const plan: CasePlan = {
		cases: [],
		skipped: { outsideRegion: 0, reviewOnly: 0, duplicate: 0 },
	};
	const seen = new Set<string>();
	for (const alert of alerts) {
		const status = eligibility(alert);
		if (status === "review-only") {
			plan.skipped.reviewOnly++;
			continue;
		}
		if (status === "outside-region") {
			plan.skipped.outsideRegion++;
			continue;
		}
		const payload = buildCase(alert);
		if (seen.has(payload.externalRef)) {
			plan.skipped.duplicate++;
			continue;
		}
		seen.add(payload.externalRef);
		plan.cases.push({ alertId: alert.id, payload });
	}
	return plan;
}

export interface CaseCreationResult {
	eligible: number;
	created: number;
	failed: number;
	skipped: CasePlan["skipped"];
	cases: Array<{ alertId: number; caseId: string; externalRef: string }>;
	errors: Array<{ alertId: number; error: string }>;
}

/** Create one TheHive case per eligible alert; transport failures stay local. */
export async function createCases(
	alerts: readonly TheHiveAlert[],
	client: TheHiveClient,
): Promise<CaseCreationResult> {
	const plan = planCases(alerts);
	const result: CaseCreationResult = {
		eligible: plan.cases.length,
		created: 0,
		failed: 0,
		skipped: plan.skipped,
		cases: [],
		errors: [],
	};
	for (const { alertId, payload } of plan.cases) {
		try {
			const caseId = await client.createCase(payload);
			result.created++;
			result.cases.push({ alertId, caseId, externalRef: payload.externalRef });
		} catch (error) {
			const message = error instanceof Error ? error.message : String(error);
			result.failed++;
			result.errors.push({ alertId, error: message.slice(0, 200) });
		}
	}
	return result;
}

/** Configuration is opt-in: no URL or key means no live case creation. */
export function readTheHiveConfig(env: NodeJS.ProcessEnv = process.env): TheHiveConfig | null {
	const url = env.RADAR_THEHIVE_URL?.trim().replace(/\/+$/, "");
	const apiKey = env.RADAR_THEHIVE_API_KEY?.trim();
	if (!url || !apiKey) return null;
	if (!/^https?:\/\//i.test(url)) return null;
	return { url, apiKey };
}

/** HTTP client for TheHive 4/5 REST API. */
export function theHiveClient(config: TheHiveConfig): TheHiveClient {
	const send = config.fetch ?? fetch;
	return {
		async createCase(payload) {
			const response = await send(`${config.url}/api/case`, {
				method: "POST",
				headers: {
					"content-type": "application/json",
					authorization: `Bearer ${config.apiKey}`,
				},
				body: JSON.stringify(payload),
				signal: AbortSignal.timeout(5000),
			});
			if (!response.ok) {
				const body = await response.text().catch(() => "");
				throw new Error(`thehive HTTP ${response.status}${body ? `: ${body.slice(0, 200)}` : ""}`);
			}
			const json = (await response.json()) as { id?: unknown } | null;
			if (typeof json?.id !== "string" && typeof json?.id !== "number") {
				throw new Error("thehive: response without case id");
			}
			return String(json.id);
		},
	};
}
