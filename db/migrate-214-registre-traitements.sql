-- 214 : registre des traitements du corpus.
--
-- Chaque source active doit pouvoir justifier son traitement : base légale,
-- durée de conservation et finalité. Le registre historique n'a pas de colonne
-- `id` (sa clé est `source_id`), alors que le contrôle externe teste
-- `r.id IS NULL` : on ajoute une identité bigint unique, qui numérote les
-- lignes existantes. `source_id` reste la clé primaire pour ne pas casser
-- `runRetention`.
-- La portée (nationale, régionale, locale, internationale) est calculée par
-- l'API à partir de `region`/`department` : elle ne relève pas du registre, et
-- le nom ou la famille d'une source ne qualifient jamais sa portée.
BEGIN;

ALTER TABLE registre_traitement
  ADD COLUMN IF NOT EXISTS id bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  ADD COLUMN IF NOT EXISTS base_legale text NOT NULL DEFAULT 'Intérêt légitime : observatoire de la cybermenace (art. 6.1.f)',
  ADD COLUMN IF NOT EXISTS finalite text NOT NULL DEFAULT 'Veille de sécurité : détection, qualification et documentation des incidents cyber';

-- Amorçage : toute source active possède une ligne ; les durées déjà déclarées
-- ne sont jamais écrasées.
INSERT INTO registre_traitement (source_id, duree_jours)
SELECT s.id, 90
  FROM source s
 WHERE s.enabled
ON CONFLICT (source_id) DO NOTHING;

-- La finalité suit la famille de la source, avec un libellé générique pour les
-- familles inconnues. Aucun libellé n'infère une portée géographique.
UPDATE registre_traitement r
   SET finalite = CASE s.family
         WHEN 'cti' THEN 'Veille CTI : collecte et qualification des indicateurs de menace'
         WHEN 'presse' THEN 'Surveillance de la presse : suivi des articles et communiqués'
         WHEN 'presse_cyber' THEN 'Surveillance de la presse spécialisée en cybersécurité'
         WHEN 'radio' THEN 'Surveillance des médias : suivi des émissions et bulletins'
         WHEN 'tv' THEN 'Surveillance des médias : suivi des journaux et reportages'
         WHEN 'institutionnel' THEN 'Suivi des publications institutionnelles'
         WHEN 'official_statement' THEN 'Suivi des avis officiels et communiqués de sécurité'
         WHEN 'cert' THEN 'Suivi des avis officiels des centres de réponse à incidents'
         WHEN 'cert_fr' THEN 'Suivi des avis officiels des autorités françaises'
         WHEN 'juridique' THEN 'Veille juridique : suivi des textes et décisions de justice'
         WHEN 'vuln' THEN 'Suivi des vulnérabilités et des correctifs de sécurité'
         WHEN 'ransomware' THEN 'Veille rançongiciel : suivi des groupes et des campagnes'
         WHEN 'phishing' THEN 'Détection phishing : suivi des campagnes et des sites trompeurs'
         WHEN 'leaks' THEN 'Détection de fuites : suivi des données divulguées'
         WHEN 'paste' THEN 'Détection d''indicateurs de fuite dans les dépôts de textes'
         WHEN 'reputation' THEN 'Surveillance de la réputation et des indicateurs de menace'
         WHEN 'forum' THEN 'Surveillance des forums : détection d''indicateurs et de discussions'
         WHEN 'association_securite' THEN 'Veille sectorielle : suivi des associations de sécurité'
         WHEN 'club_entreprises' THEN 'Veille sectorielle : suivi des clubs d''entreprises'
         WHEN 'cci' THEN 'Veille sectorielle : suivi des chambres de commerce et d''industrie'
         ELSE 'Veille de sécurité : détection, qualification et documentation des incidents cyber'
       END
  FROM source s
 WHERE r.source_id = s.id;

-- Toute source qui devient active est déclarée aussitôt. Une ligne existante
-- est laissée intacte : sa durée et sa finalité restent sous la responsabilité
-- de la déclaration initiale.
CREATE OR REPLACE FUNCTION registre_traitement_source_active()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.enabled AND (TG_OP = 'INSERT' OR OLD.enabled = false) THEN
    INSERT INTO registre_traitement (source_id, duree_jours, finalite)
    VALUES (
      NEW.id,
      90,
      CASE NEW.family
        WHEN 'cti' THEN 'Veille CTI : collecte et qualification des indicateurs de menace'
        WHEN 'presse' THEN 'Surveillance de la presse : suivi des articles et communiqués'
        WHEN 'presse_cyber' THEN 'Surveillance de la presse spécialisée en cybersécurité'
        WHEN 'radio' THEN 'Surveillance des médias : suivi des émissions et bulletins'
        WHEN 'tv' THEN 'Surveillance des médias : suivi des journaux et reportages'
        WHEN 'institutionnel' THEN 'Suivi des publications institutionnelles'
        WHEN 'official_statement' THEN 'Suivi des avis officiels et communiqués de sécurité'
        WHEN 'cert' THEN 'Suivi des avis officiels des centres de réponse à incidents'
        WHEN 'cert_fr' THEN 'Suivi des avis officiels des autorités françaises'
        WHEN 'juridique' THEN 'Veille juridique : suivi des textes et décisions de justice'
        WHEN 'vuln' THEN 'Suivi des vulnérabilités et des correctifs de sécurité'
        WHEN 'ransomware' THEN 'Veille rançongiciel : suivi des groupes et des campagnes'
        WHEN 'phishing' THEN 'Détection phishing : suivi des campagnes et des sites trompeurs'
        WHEN 'leaks' THEN 'Détection de fuites : suivi des données divulguées'
        WHEN 'paste' THEN 'Détection d''indicateurs de fuite dans les dépôts de textes'
        WHEN 'reputation' THEN 'Surveillance de la réputation et des indicateurs de menace'
        WHEN 'forum' THEN 'Surveillance des forums : détection d''indicateurs et de discussions'
        WHEN 'association_securite' THEN 'Veille sectorielle : suivi des associations de sécurité'
        WHEN 'club_entreprises' THEN 'Veille sectorielle : suivi des clubs d''entreprises'
        WHEN 'cci' THEN 'Veille sectorielle : suivi des chambres de commerce et d''industrie'
        ELSE 'Veille de sécurité : détection, qualification et documentation des incidents cyber'
      END
    )
    ON CONFLICT (source_id) DO NOTHING;
  END IF;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS registre_traitement_source_active ON source;
CREATE TRIGGER registre_traitement_source_active
  AFTER INSERT OR UPDATE OF enabled ON source
  FOR EACH ROW EXECUTE FUNCTION registre_traitement_source_active();

COMMENT ON TABLE registre_traitement IS
  'Registre des traitements du corpus : base légale, durée de conservation et finalité déclarées par source. La portée géographique est calculée par l''API et ne figure pas ici.';
COMMENT ON COLUMN registre_traitement.id IS
  'Identifiant unique de la ligne de registre (identité bigint), utilisé par les contrôles externes ; source_id reste la clé de référence.';
COMMENT ON COLUMN registre_traitement.base_legale IS
  'Base légale du traitement (intérêt légitime : observatoire de la cybermenace, art. 6.1.f).';
COMMENT ON COLUMN registre_traitement.finalite IS
  'Finalité du traitement selon la famille de la source, ou libellé générique. Nationalité et portée géographique d''une source ne sont pas des finalités.';

COMMIT;
